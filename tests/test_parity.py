"""Cross-language parity: this package must agree with the JavaScript one.

Both READMEs tell the reader that "a string prepared on either side of a project
is byte-identical". Until 2026-09-10 that sentence described a test suite that
did not exist, and the claim was false: the two packages disagreed on five
inputs, because this side used ``str.lstrip()`` (which strips every Unicode
space) where the JavaScript side spells out a narrow class.

The fixture is generated by ``tools/build_parity_fixture.py``, which runs both
implementations and refuses to write anything unless they already agree. This
test asserts this side still matches it. The same fixture is committed to the
rtl-ui repository and asserted there, so a drift in either language fails a
test rather than being absorbed the next time the fixture is regenerated.
"""
import json
import pathlib
import unittest

import tervatrix_rtl

FIXTURE = pathlib.Path(__file__).with_name("parity_fixture.json")


class ParityWithJavaScript(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.cases = json.loads(FIXTURE.read_text(encoding="utf-8"))["cases"]

    def test_fixture_is_present_and_populated(self):
        self.assertGreaterEqual(
            len(self.cases), 20, "the parity fixture has lost cases"
        )

    def test_fixture_still_probes_the_whitespace_boundary(self):
        """A parity fixture that stopped containing the awkward characters would
        pass for the wrong reason. These are the codepoints that separate the
        two implementations' leading-whitespace classes, and at least one case
        must still carry each of them."""
        stripped_by_both = (0x00A0, 0x000B, 0x000C, 0x000D)
        stripped_by_neither = (0x2000, 0x3000, 0x2009, 0x0085, 0x1680)
        inputs = [c["input"] for c in self.cases]
        for codepoint in stripped_by_both + stripped_by_neither:
            with self.subTest(codepoint=f"U+{codepoint:04X}"):
                self.assertTrue(
                    any(chr(codepoint) in text for text in inputs),
                    f"no case carries U+{codepoint:04X} any more",
                )

    def test_prepare_outbound_matches_the_javascript_output(self):
        for case in self.cases:
            with self.subTest(case=case["name"]):
                language = case["language"]
                actual = (
                    tervatrix_rtl.prepare_outbound(case["input"])
                    if language is None
                    else tervatrix_rtl.prepare_outbound(case["input"], language)
                )
                self.assertEqual(
                    actual,
                    case["prepare"],
                    f"{case['name']}: python {ascii(actual)} != "
                    f"javascript {ascii(case['prepare'])}",
                )

    def test_isolate_ltr_runs_matches_the_javascript_output(self):
        for case in self.cases:
            with self.subTest(case=case["name"]):
                self.assertEqual(
                    tervatrix_rtl.isolate_ltr_runs(case["input"]),
                    case["isolate_runs"],
                    case["name"],
                )

    def test_strip_bidi_matches_the_javascript_output(self):
        for case in self.cases:
            with self.subTest(case=case["name"]):
                self.assertEqual(
                    tervatrix_rtl.strip_bidi(case["prepare"]),
                    case["strip"],
                    case["name"],
                )

    def test_leading_whitespace_class_matches_the_javascript_one(self):
        """The regression itself, stated directly rather than only through the
        fixture: these four are looked past when deciding whether a line already
        starts right to left, and these five are not."""
        for codepoint in (0x0020, 0x0009, 0x000B, 0x000C, 0x000D, 0x00A0):
            with self.subTest(strips=f"U+{codepoint:04X}"):
                line = chr(codepoint) + "שלום"
                self.assertEqual(
                    tervatrix_rtl.force_rtl_paragraphs(line),
                    line,
                    f"U+{codepoint:04X} should be looked past, so no RTL mark",
                )
        for codepoint in (0x2000, 0x3000, 0x2009, 0x0085, 0x1680):
            with self.subTest(keeps=f"U+{codepoint:04X}"):
                line = chr(codepoint) + "שלום"
                self.assertEqual(
                    tervatrix_rtl.force_rtl_paragraphs(line),
                    tervatrix_rtl.RLM + line,
                    f"U+{codepoint:04X} is not in the class, so the line takes "
                    f"an RTL mark",
                )


if __name__ == "__main__":
    unittest.main()
